const localeMessages: Partial<Record<InterfaceLanguage, Record<I18nKey, string>>> = {
  en: enMessages,
  "zh-CN": zhCNMessages,
  "zh-TW": zhTWMessages
};

export const languageOptions: Array<{ value: InterfaceLanguage; label: string; code: string }> = [
  { value: "zh-CN", label: "简体中文", code: "zh-CN" },
  { value: "zh-TW", label: "繁體中文", code: "zh-TW" },
  { value: "en", label: "English", code: "en" }
];

export function createTranslator(language: InterfaceLanguage): Translator {
  const messages = localeMessages[language] ?? enMessages;
  return (key, values) => interpolate(messages[key] ?? enMessages[key] ?? zhCNMessages[key], values);
}

function interpolate(template: string, values?: TranslationValues) {
  if (!values) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (_, key: string) => String(values[key] ?? `{${key}}`));
}
