#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const desktopRoot = path.resolve(scriptDir, "..");
const outputPath = path.join(desktopRoot, "src/main/generated-runtime-defaults.ts");

function firstEnv(keys, fallback) {
  for (const key of keys) {
    const value = process.env[key]?.trim();
    if (value) return value;
  }
  return fallback;
}

const webBaseUrl = firstEnv(["MKBOARD_WEB_URL", "PUBLIC_WEB_URL"], "https://github.com/yihui-dev/mkboard.app");
const autoUpdateBaseUrl = firstEnv(["MKBOARD_AUTO_UPDATE_BASE_URL"], "");

const next = `// Generated by apps/desktop/scripts/write-runtime-defaults.mjs. Do not edit.
export const packagedReleaseTarget = "oss" as const;
export const packagedWebBaseUrl = ${JSON.stringify(webBaseUrl)};
export const packagedAutoUpdateBaseUrl = ${JSON.stringify(autoUpdateBaseUrl)};
`;

mkdirSync(path.dirname(outputPath), { recursive: true });
let previous = null;
try {
  previous = readFileSync(outputPath, "utf8");
} catch {
  previous = null;
}
if (previous !== next) writeFileSync(outputPath, next);
console.log(`Desktop runtime defaults: target=oss web=${webBaseUrl} autoUpdate=${autoUpdateBaseUrl || "disabled (community build)"}`);
